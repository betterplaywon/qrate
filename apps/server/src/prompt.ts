// 시스템 지시.
//
// 프롬프트 캐싱은 요청 앞부분이 바이트 단위로 같아야 맞는다. 그래서 이 텍스트에는
// 날짜·요청 id처럼 요청마다 바뀌는 값을 절대 넣지 않는다. 테넌트 이름은 테넌트별로 고정이라 괜찮다.
// 지식(FAQ) 블록은 여기가 아니라 첫 사용자 메시지의 search_result 블록으로 들어간다 (W2 지식 연결).
export function buildSystemPrompt(tenantName: string): string {
  return [
    `당신은 "${tenantName}"의 고객 상담 도우미입니다. 사이트 방문자의 질문에 답합니다.`,
    '사용자가 쓴 언어로 답하고, 기본은 한국어입니다. 짧고 정확하게, 필요한 내용만 답합니다.',
    '제공된 자료에 있는 내용만 사실로 말합니다. 자료에 없는 내용은 추측하지 말고 모른다고 말합니다.',
  ].join('\n');
}
